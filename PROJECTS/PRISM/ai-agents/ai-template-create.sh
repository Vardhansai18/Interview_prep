#!/bin/bash

###########################################################
# Script Name : ai-template-create.sh
# Description : Creates a template directory structure for
#               ai-agent projects with agents, subagents,
#               skills, instructions, input, output, logs,
#               subdirectories and a README.md describing
#               the template structure.
# Logic       : - If folder name is "common" → create in
#                 current directory
#               - Otherwise → create inside "projects/"
#                 directory
# Usage       : ./ai-template-create.sh <folder_name>
###########################################################

# Color codes for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# --------------------
# Function: usage
# --------------------
usage() {
    echo -e "${YELLOW}Usage: $0 <folder_name>${NC}"
    echo ""
    echo "  Creates a template directory structure for"
    echo "  ai-agent project with the given name and creates"
    echo "  subdirectories: agents, sugagents, skills, scripts,"
    echo "                  instructions, input, output, logs."
    echo "  Also generates a README.md describing the structure."
    echo ""
    echo "  ${CYAN}Path Logic:${NC}"
    echo "    - If folder_name is 'common' → created in current directory (./<folder_name>)"
    echo "    - Otherwise                  → created in projects directory (./projects/<folder_name>)"
    echo ""
    echo "  Example: $0 my_ai_agent_project → Creates ./projects/my_project/"
    echo "           $0 common       → Creates ./common/"
    exit 1
}

# --------------------
# Function: log message
# --------------------
log_success() {
    echo -e "${GREEN}[✔] $1${NC}"
}

log_error() {
    echo -e "${RED}[✘] $1${NC}"
}

log_info() {
    echo -e "${YELLOW}[i] $1${NC}"
}

log_path() {
    echo -e "${CYAN}[→] $1${NC}"
}

# -----------------------------
# Function: create README.md
# -----------------------------
create_readme() {
    local folder="$1"
    local display_name="$2"
    local readme_path="${folder}/README.md"
    local created_date
    created_date=$(date '+%Y-%m-%d %H:%M:%S')
    local created_by
    created_by=$(whoami)

    cat > "$readme_path" <<EOF
# 📁 ${display_name}

## Description
This directory was auto-generated using the \`ai-template-create.sh\` script.

## 📋 Folder Structure

\`\`\`
${display_name}/
├── agents/         # Main AI agent orchestrator
├── subagents/      # Subagents called from main agent
├── skills/         # Project specific domain/additional knowledge skill file
├── instructions/   # Project specific instruction file used by agent/subagent
├── input/          # Input files used by agent/subagent
├── output/         # Processed output and results
├── logs/           # Log files and execution records
├── scripts/        # Scripts needed by agents/subagents
└── README.md       # Project documentation (design/user manual)
\`\`\`

## 📂 Directory Details

| Directory          | Purpose                                                           |
|--------------------|-------------------------------------------------------------------|
| \`agents/\`        | Store main AI orchestrator and other agent files                  |
| \`subagents/\`     | Store subagents file called from main agent                       |
| \`skills/\`        | Store project specific skills needed by agent/subagent            |
| \`instructions/\`  | Store project specific instructions file used by agent/subagent   |
| \`input/\`         | Store all input files, raw data, and resources                    |
| \`output/\`        | Store processed results, reports, and artifacts                   |
| \`logs/\`          | Store log files, execution history, and debug info                |
| \`scripts/\`       | Store scripts that are used by agents/subagents                   |

## 📝 Usage Guidelines

1. Place AI agent files in the \`agents/\` directory
2. Place all subagents files in the \`subagents/\` directory
3. Place all project specifc *.SKILL.md files in the \`skills/\` directory
4. Place all project specific *.instruction.md files in the \`input/\` directory
5. Place all source/input files in the \`input/\` directory
6. All generated output should be written to the \`output/\` directory
7. Application and script logs should be directed to the \`logs/\` directory
8. Update this README.md with project-specific details as needed

## ℹ️ Metadata

| Field        | Value                 |
|--------------|-----------------------|
| Folder Name  | ${display_name}       |
| Full Path    | ${folder}             |
| Created By   | ${created_by}         |
| Created On   | ${created_date}       |
| Generated By | ai-template-create.sh |

---
> **Note**: This README was auto-generated. Please update it with your project-specific information.
EOF

    if [ $? -ne 0 ]; then
        log_error "Failed to create README.md in '${folder}'"
        return 1
    fi

    log_success "Created README.md        : ${folder}/README.md"
    return 0
}

# --------------------
# Validate input
# --------------------
if [ $# -ne 1 ]; then
    log_error "No folder name provided!"
    usage
fi

FOLDER_NAME="$1"

# Check for invalid characters in folder name
if [[ "$FOLDER_NAME" =~ [^a-zA-Z0-9_\-\.] ]]; then
    log_error "Invalid folder name: '${FOLDER_NAME}'"
    echo "    Allowed characters: letters, numbers, underscore (_), hyphen (-), dot (.)"
    exit 1
fi

# --------------------
# Determine target path
# --------------------
PROJECTS_DIR="projects"

if [ "$FOLDER_NAME" == "common" ]; then
    # Create in current directory
    TARGET_PATH="./${FOLDER_NAME}"
    log_info "Folder name is 'common' → Creating in current directory"
else
    # Create inside projects/ directory
    TARGET_PATH="./${PROJECTS_DIR}/${FOLDER_NAME}"
    log_info "Folder name is '${FOLDER_NAME}' → Creating inside '${PROJECTS_DIR}/' directory"

    # Create projects directory if it doesn't exist
    if [ ! -d "$PROJECTS_DIR" ]; then
        mkdir -p "$PROJECTS_DIR"
        if [ $? -ne 0 ]; then
            log_error "Failed to create '${PROJECTS_DIR}' directory"
            exit 1
        fi
        log_success "Created projects directory: ${PROJECTS_DIR}/"
    fi
fi

log_path "Target path: ${TARGET_PATH}"
echo ""

# Check if directory already exists
if [ -d "$TARGET_PATH" ]; then
    log_error "Directory '${TARGET_PATH}' already exists!"
    log_info "Please provide a different folder name or remove the existing directory."
    exit 1
fi

# --------------------
# Create directories
# --------------------
SUB_DIRS=("agents" "subagents" "skills" "instructions" "input" "output" "logs" "scripts")

log_info "Creating ai-agent template for project '${FOLDER_NAME}'..."
echo ""

# Create parent directory
mkdir -p "$TARGET_PATH"
if [ $? -ne 0 ]; then
    log_error "Failed to create directory '${TARGET_PATH}'"
    exit 1
fi
log_success "Created parent directory : ${TARGET_PATH}/"

# Create subdirectories
for dir in "${SUB_DIRS[@]}"; do
    mkdir -p "${TARGET_PATH}/${dir}"
    if [ $? -ne 0 ]; then
        log_error "Failed to create subdirectory '${TARGET_PATH}/${dir}'"
        exit 1
    fi
    log_success "Created subdirectory     : ${TARGET_PATH}/${dir}/"
done

# Create .gitkeep files in subdirectories
#for dir in "${SUB_DIRS[@]}"; do
#    touch "${TARGET_PATH}/${dir}/.gitkeep"
#done

# Create README.md
create_readme "$TARGET_PATH" "$FOLDER_NAME"
if [ $? -ne 0 ]; then
    exit 1
fi

# --------------------
# Display summary
# --------------------
echo ""
echo "========================================================================="
echo "  AI-AGENT template for project ${FOLDER_NAME} Created"
echo "========================================================================="
echo ""
tree -a "$TARGET_PATH" 2>/dev/null || {
    # Fallback if 'tree' command is not installed
    echo "  ${TARGET_PATH}/"
    for dir in "${SUB_DIRS[@]}"; do
        echo "  ├── ${dir}/"
#echo "  │   └── .gitkeep"
    done
    echo "  └── README.md"
}
echo ""
log_success "AI-AGENT template for project ${FOLDER_NAME} and README.md are created successfully!"
log_success "Trust, but verify! Happy Coding with Agent!!"
echo ""

exit 0
